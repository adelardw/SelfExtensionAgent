from pydantic import BaseModel, Field
from typing import Literal


class RouteDecision(BaseModel):
    """Выход роутера — определяет какую ветку графа использовать."""
    reasoning: str = Field(description="Краткое обоснование выбранного маршрута")
    route: Literal["create_skill", "use_skills"] = Field(
        description="'create_skill' — ни один существующий навык не подходит, "
                    "'use_skills' — существующие навыки покрывают задачу"
    )


class SkillSelection(BaseModel):
    """Выход селектора навыков — выбирает подходящие навыки из реестра."""
    reasoning: str = Field(description="Почему выбраны именно эти навыки")
    selected_skills: list[str] = Field(
        description="Точные snake_case имена навыков из реестра"
    )


class ExecutionPlan(BaseModel):
    """Выход планировщика — упорядоченные шаги выполнения."""
    reasoning: str = Field(description="Общий подход к решению задачи")
    steps: list[str] = Field(description="Конкретные, упорядоченные шаги выполнения")


class NodeGradient(BaseModel):
    """Текстовый «градиент» одной ноды: как ИМЕННО ей стоит измениться."""
    node: str = Field(description="Имя ноды графа (из списка оптимизируемых)")
    critique: str = Field(description="Конкретно что нода делает не так и как улучшить (её локальный градиент)")


class NodeGradients(BaseModel):
    """Backward по графу: распределённые по нодам текстовые градиенты из батча неудач."""
    gradients: list[NodeGradient] = Field(
        description="Только для нод, реально виноватых в неудачах. Не вали вину на ноды, "
                    "которые отработали корректно. Пусто — если винить нечего.",
        default_factory=list,
    )


class UserLesson(BaseModel):
    """Персональный урок из неудач КОНКРЕТНОГО пользователя — корректирующий few-shot."""
    node: str = Field(description="Имя ноды графа (из каталога), к которой относится урок")
    trigger: str = Field(description="ТИП запроса этого пользователя, где нода ошибалась "
                                     "(короткий обобщённый паттерн, как пример-запрос, НЕ дословная копия)")
    lesson: str = Field(description="Как ИМЕННО стоит вести себя с ЭТИМ пользователем на таких запросах "
                                    "(с учётом кто он). Конкретный образец правильного поведения/ответа.")


class UserLessons(BaseModel):
    """Per-user backward: уроки из неудач пользователя, обусловленные тем, КТО он."""
    lessons: list[UserLesson] = Field(
        description="Только там, где видна реальная повторяющаяся ошибка под этого пользователя. "
                    "Пусто — если винить нечего или данных мало.",
        default_factory=list,
    )


class CognitiveAssessment(BaseModel):
    """
    Единый «акт мышления»: за ОДИН вызов и понять цель, и выбрать режим.
    Слияние goal+reflexion ради бюджета (2 LLM-вызова → 1) — и это когнитивно
    честнее: человек оценивает суть задачи и «как думать» одновременно.
    """
    # — цель —
    aim: str = Field(description="Краткая формулировка намерения текущего запроса")
    is_standing: bool = Field(description="Это многошаговая/долгая цель, которую держать в контексте?")
    completes_active: bool = Field(description="Запрос завершает активную стоящую цель?", default=False)
    standing_goal: str = Field(description="Текст стоящей цели для удержания (если is_standing), иначе ''", default="")
    success_criteria: list[str] = Field(
        description="Rubric цели: проверяемый чек-лист (для is_standing), иначе пусто", default_factory=list
    )
    # — режим мышления —
    mode: Literal["fast", "deliberate", "clarify"] = Field(
        description="'fast' — быстрый интуитивный ответ без инструментов; "
                    "'deliberate' — обдумывание с инструментами/многошаговостью/свежими данными; "
                    "'clarify' — переспросить при неоднозначности. Бюджет важен: не уходи в deliberate зря."
    )
    needs_tools: bool = Field(description="Нужны ли внешние инструменты/навыки")


class ReflexionDecision(BaseModel):
    """
    Self-Reflexion Choice: выбор режима мышления (модель System 1 / System 2).
    Главный рычаг бюджета — не гонять дорогой путь там, где хватит быстрого.
    """
    mode: Literal["fast", "reason", "act", "deliberate", "heavy", "clarify"] = Field(
        description="Режим/тип мышления по анализу задачи: "
                    "'fast' — быстрый интуитивный ответ без инструментов (приветствия, простое, известное); "
                    "'reason' — глубокое пошаговое рассуждение БЕЗ инструментов (сложные вопросы, "
                    "анализ, математика, логика — где думать надо много, но внешние данные не нужны); "
                    "'act' — ОДНО ПРОСТОЕ ПРЯМОЕ действие с устройством/приложением «здесь и сейчас» "
                    "(открой сайт/почту/приложение, сделай скриншот, набери текст, покажи уведомление): "
                    "исполняется сразу 1–2 вызовами инструментов, БЕЗ планирования и исследования; "
                    "если действий цепочка, нужны данные из веба или собирается артефакт — deliberate; "
                    "'deliberate' — обдумывание с инструментами/навыками, многошаговостью, свежими данными; "
                    "'heavy' — БОЛЬШАЯ/тяжёлая задача (артефакт из многих частей, проект, длинный документ): "
                    "как deliberate, но после сборки результата идёт сквозной ревью всего решения "
                    "и раунд доработки найденных проблем — дороже, используй только когда задача реально большая; "
                    "'clarify' — задача неоднозначна, дешевле переспросить."
    )
    needs_tools: bool = Field(description="Нужны ли внешние инструменты/навыки для ответа")
    rationale: str = Field(description="Кратко почему выбран этот режим")
    mode_confidence: float = Field(
        description="Насколько ты УВЕРЕН, что выбран ПРАВИЛЬНЫЙ режим (0.0 — сомневаюсь между "
                    "режимами; 1.0 — очевидно). Честно: при пограничном выборе ставь ниже.",
        ge=0.0, le=1.0, default=0.8,
    )
    ambiguity: float = Field(
        description="Насколько запрос НЕОДНОЗНАЧЕН/недоопределён, 0.0 (всё ясно) – 1.0 (непонятно что хотят). "
                    "Высокое значение → дешевле переспросить, чем гадать (ambiguity-гейт).",
        ge=0.0, le=1.0, default=0.0,
    )
    missing_info: str = Field(
        description="Если ambiguity высокая — какой ИМЕННО информации не хватает (для точного уточняющего вопроса).",
        default="",
    )
    grounding: float = Field(
        description="Для mode='reason'/'fast': насколько ДОСТОВЕРНО ты можешь ответить из СОБСТВЕННЫХ "
                    "знаний/памяти/условия задачи БЕЗ внешних данных — есть ли надёжные ОСНОВАНИЯ "
                    "(устойчивое знание, факты в памяти, данные прямо в запросе). 1.0 — уверен в "
                    "основаниях; 0.0 — базы нет, легко выдумать. Будь ЧЕСТЕН: при сомнении в фактах, "
                    "свежести, точных числах/именах/узкой теме ставь НИЗКО — лучше заземлиться через "
                    "инструменты, чем галлюцинировать. (Приветствия/простое/данные-в-условии = высоко.)",
        ge=0.0, le=1.0, default=1.0,
    )


class ClarificationItem(BaseModel):
    """Один блокирующий вопрос к пользователю с гибким форматом ответа."""
    question: str = Field(description="Точный вопрос — что именно неясно и мешает сделать правильно")
    options: list[str] = Field(
        description="Варианты-маркеры, ЕСЛИ набор ответов конечен (2–4 коротких варианта). "
                    "Пустой список — если вопрос открытый (нет заранее известных вариантов).",
        default_factory=list,
    )
    assume: str = Field(
        description="Самое вероятное допущение по умолчанию — что взять, если пользователь не ответит."
    )


class ClarificationSet(BaseModel):
    """
    Батч уточнений ПЕРЕД исполнением. Только РЕАЛЬНО блокирующее: без чего нельзя
    сделать правильно. Если всё ясно из запроса/памяти — пустой список (не выдумывай).
    """
    items: list[ClarificationItem] = Field(
        description="0–4 действительно блокирующих вопроса. Пусто, если уточнять нечего.",
        default_factory=list,
    )


class SubTask(BaseModel):
    """Один пункт плана (атомарный подшаг декомпозиции)."""
    goal: str = Field(description="Что конкретно сделать на этом шаге — одно атомарное действие")
    done_check: str = Field(description="Проверяемый критерий, что шаг выполнен (мини-rubric шага)")
    kind: Literal["direct", "research", "compose"] = Field(
        default="research",
        description="ТИП исполнения шага (важно для скорости/бюджета): "
                    "'direct' — один вызов инструмента или короткое действие (сохранить/посчитать/"
                    "открыть/найти один факт) — БОЛЬШИНСТВО шагов; "
                    "'research' — нужна итеративная работа с инструментами (искать→читать несколько→синтез); "
                    "'compose' — собрать/синтезировать результат из ПРЕДЫДУЩИХ шагов БЕЗ инструментов. "
                    "По умолчанию ставь 'direct', если шагу не нужна именно многошаговая работа с тулами.",
    )


class TaskDecomposition(BaseModel):
    """
    Смешанный формат: связный ризонинг, ВНУТРИ которого рождается план.
    reasoning — рассуждение о подходе; subtasks — извлечённые из него пункты.
    """
    reasoning: str = Field(description="Связное рассуждение о подходе, по ходу которого формируется план")
    subtasks: list[SubTask] = Field(description="Упорядоченные атомарные подшаги (обычно 1–6)")


class IntegrationReview(BaseModel):
    """
    Heavy-режим: сквозной ревью СОБРАННОГО решения целиком (а не отдельных шагов).
    Смотрит на полный пайплайн «запрос → шаги → финал» и находит интеграционные
    проблемы: пропуски, противоречия между шагами, несоответствие исходной задаче.
    """
    passed: bool = Field(description="Решение целостно и полностью закрывает исходную задачу?")
    problems: list[str] = Field(
        description="Конкретные интеграционные проблемы (пропуски/противоречия/несоответствия). Пусто если passed.",
        default_factory=list,
    )
    fix_subtasks: list[SubTask] = Field(
        description="1–3 атомарных подшага доработки, закрывающих найденные проблемы. Пусто если passed.",
        default_factory=list,
    )


class SkillRetention(BaseModel):
    """Решение о судьбе ВРЕМЕННОГО навыка после решения задачи: оставить в библиотеке или выбросить."""
    keep: bool = Field(
        description="True — навык переиспользуем для БУДУЩИХ задач (общий, не одноразовый); "
                    "False — одноразовый под конкретный запрос, держать в библиотеке не нужно."
    )
    reason: str = Field(description="Краткое обоснование решения")


class DistillVerdict(BaseModel):
    """Судья ретроспективной дистилляции: стоит ли выделять навык из траектории УСПЕШНОГО прогона.
    Дешёвый гейт ПЕРЕД create_skills_agent (его системный промпт императивно велит «создать» —
    сам он не откажется)."""
    worth: bool = Field(
        description="True — из траектории выделяется ПЕРЕИСПОЛЬЗУЕМАЯ программируемая способность, "
                    "которой НЕТ среди существующих навыков; False — одноразовая задача, "
                    "непрограммируемая последовательность или дубликат существующего навыка."
    )
    capability: str = Field(
        description="Если worth: одно предложение — какую способность выделить (для ТЗ инженеру "
                    "навыков). Иначе пустая строка.")
    reason: str = Field(description="Краткое обоснование решения")


class StepOutcome(BaseModel):
    """По-пунктовая валидация: пройден ли подшаг по своему done_check."""
    passed: bool = Field(description="Подшаг выполнен и удовлетворяет done_check?")
    note: str = Field(description="Что получилось / в чём проблема (для ретрая или контекста след. шага)")


class SGRCreateResult(BaseModel):
    """Результат ревью созданного навыка (SGR ветки создания)."""
    is_valid: bool = Field(description="Навык корректный, полный и готов к использованию?")
    confidence: float = Field(description="Уверенность 0.0–1.0", ge=0.0, le=1.0)
    issues: list[str] = Field(description="Найденные проблемы (пусто если валидный)", default_factory=list)
    suggestion: str = Field(description="Как исправить проблемы (пусто если валидный)", default="")


class SkillTestCase(BaseModel):
    """Тестовый кейс для smoke-теста навыка."""
    tool_name: str = Field(
        description="Имя @tool функции для тестирования (то, что передано в декоратор @tool или имя функции)"
    )
    test_input: dict = Field(
        description="Аргументы для вызова: {имя_параметра: тестовое_значение}. "
                    "Используй простые, быстрые, реалистичные значения."
    )
    expected_behavior: str = Field(
        description="Краткое описание ожидаемого поведения (для логирования)"
    )


class ValidationResult(BaseModel):
    """Финальная валидация ответа агента (SGR конца графа)."""
    is_valid: bool = Field(description="Ответ полностью соответствует запросу пользователя?")
    confidence: float = Field(description="Уверенность 0.0–1.0", ge=0.0, le=1.0)
    feedback: str = Field(description="Краткая оценка качества ответа")
    # Анти-галлюцинация семантически (любой язык) — вместо регэкспов в коде. Судья и так читает
    # финал, поэтому ловит это без отдельного вызова.
    false_refusal: bool = Field(
        default=False,
        description="Ответ ЛОЖНО заявляет «нет доступа к аккаунтам/личным данным/вебу/сервису»? "
                    "У агента доступ ЕСТЬ через расширение браузера — такой отказ это галлюцинация "
                    "под давлением, НЕ настоящее ограничение. Честное «не нашёл результата» или "
                    "«нужно подтверждение/вход» — это НЕ false_refusal.")
    meta_stub: bool = Field(
        default=False,
        description="Ответ — мета-заглушка ВМЕСТО результата («я перечислил выше / список выше / "
                    "задача выполнена / done») без самого содержимого, которое просил пользователь? "
                    "Реальный результат со списком/данными — НЕ meta_stub.")
    false_completion: bool = Field(
        default=False,
        description="Дан run_status=incomplete (прогон ОБОРВАН бюджетом/незавершён), а ответ "
                    "заявляет, что действие ВЫПОЛНЕНО (добавил/заказал/оформил/включил/отправил/"
                    "готово)? Тогда это ложь о завершении. Если run_status=complete — ВСЕГДА false "
                    "(поле только про оборванный прогон, не про качество).")


class UserFact(BaseModel):
    """Один устойчивый факт о пользователе (семантическая память / персонализация)."""
    key: str = Field(description="Короткий стабильный ключ в snake_case, напр. 'язык_общения', 'часовой_пояс', 'предпочитаемый_стек'")
    value: str = Field(description="Значение факта одной фразой")
    importance: float = Field(description="Насколько это важно для долгой памяти, 0.0–1.0", ge=0.0, le=1.0, default=0.5)
    tags: list[str] = Field(
        description="1–3 тега-темы для группировки и связного поиска (напр. 'работа', 'личное', 'стек', 'предпочтения')",
        default_factory=list,
    )


