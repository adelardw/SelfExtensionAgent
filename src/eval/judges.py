def build_prompt(judge_id: str, thread: str, extra_context: str = "") -> str:
    """Полный промпт сабагента-судьи: персона + сценарий + инструкция драйвера + формат вердикта."""
    j = JUDGES[judge_id]
    steps = "\n".join(f"{i}. {s}" for i, s in enumerate(j["steps"], 1))
    return (
        f"Ты — независимый валидатор AI-агента «SEA». Угол: {j['title']}.\n"
        f"{j['persona']}\n\n"
        f"Сценарий ({len(j['steps'])} ходов, адаптируй реплики под реальные ответы агента):\n"
        f"{steps}\n\n"
        f"{DRIVER_HOWTO.format(thread=thread)}"
        f"{(chr(10) + extra_context + chr(10)) if extra_context else ''}"
        f"{VERDICT_TAIL.format(extra=j['extra'])}"
    )


def list_judges() -> list[tuple[str, str, str]]:
    """[(id, title, model_hint)] — для выбора состава раунда."""
    return [(k, v["title"], v["model_hint"]) for k, v in JUDGES.items()]
