"""
Implicit Feedback — оценка удовлетворённости пользователя без явных оценок.

Принцип (см. дизайн-заметки): сигнал неявной обратной связи ОЧЕНЬ шумный,
поэтому здесь он формируется как ГИПОТЕЗА для исполнителя ("возможно, прошлый
ответ не зашёл — попробуй иначе"), а НЕ как жёсткая награда, меняющая поведение.
Превращение этого в reward-модель/персонализацию — задача evolutionary-контура.

Сейчас детектируем самый сильный сигнал: переспрашивание похожей задачи,
по которой прошлый ответ был неуверенным (low confidence).
"""
from __future__ import annotations

from .store import MemoryStore, _overlap

# Насколько похожим должен быть запрос, чтобы счесть его переформулировкой.
# 0.55, не ниже: при 0.35 «саммари README.md» матчился со слабым «саммари ARCHITECTURE.md»
# (другой файл!) → ложный негативный сигнал каскадно дорог (amortize-бенч вскрыл: блокирует
# компиляцию рецепта и толкает исполнителя «зайти иначе» — 49с → 130с, +14k токенов).
_REPEAT_SIM = 0.55

# Маркер негативного сигнала — общий для detect() и потребителей (чтобы не
# матчить формулировку строками в разных местах).
_NEG_MARK = "[neg]"


def is_negative(signal: str) -> bool:
    """True, если гипотеза implicit feedback негативная (прошлый ответ не зашёл)."""
    return signal.startswith(_NEG_MARK)


def strip_marker(signal: str) -> str:
    """Убирает служебный маркер перед инъекцией в промпт."""
    return signal[len(_NEG_MARK):].lstrip() if signal.startswith(_NEG_MARK) else signal


def detect(store: MemoryStore, user_id: str, query: str, low_conf: float) -> str:
    """
    Возвращает текстовую гипотезу о неявной обратной связи (или "").
    Инъектируется в execution как подсказка, не как директива.
    """
    recent = store.recent_episodes(user_id, n=5)
    for ep in recent:
        sim = _overlap(query, ep["query"])
        if sim < _REPEAT_SIM:
            continue
        if (ep["confidence"] or 1.0) < low_conf or ep["outcome"] != "ok":
            return (
                _NEG_MARK + " Пользователь, похоже, переспрашивает задачу, по которой прошлый "
                "ответ был слабым. НЕ повторяй прежний подход — зайди с другой "
                "стороны, уточни детали или используй другой инструмент."
            )
        return (
            "Похожая задача уже успешно решалась раньше — переиспользуй прошлый "
            "подход и будь консистентен с предыдущим ответом."
        )
    return ""
