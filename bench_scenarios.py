def _flatten():
    # Тяжёлые play-категории (фильмы/музыка — без браузера в eval флейлят по 60с) — В КОНЕЦ,
    # лёгкий headless-ресёрч ПЕРВЫМ: если прогон прервётся, ценные данные уже на диске.
    last = {"фильмы_кино", "музыка"}
    order = [c for c in SCENARIOS if c not in last] + [c for c in SCENARIOS if c in last]
    out = []
    for cat in order:
        for q in SCENARIOS[cat]:
            out.append((cat, q))
    return out


_URL = re.compile(r"https?://[^\s)\]}>\"']+")
_REFUSAL = re.compile(r"не имею доступа|не могу получить доступ|нет доступа к|не удалось|"
                      r"не получилось|извините", re.I)


_WLOCK = asyncio.Lock()
_OUT = "/tmp/bench_results.jsonl"


async def _run_one(graph, cat, q, sem):
    import src.agent as A
    async with sem:
        t0 = time.time()
        rec = {"cat": cat, "q": q, "should_ground": A._needs_web_grounding(q),
               "phys": A._wants_physical_browser(q)}
        try:
            sid = str(uuid.uuid4())
            r = await asyncio.wait_for(graph.ainvoke(
                {"query": q, "user_id": "bench", "session_id": sid, "chat_history": [{"role": "user", "content": q}]},
                config={"configurable": {"thread_id": sid}, "recursion_limit": 50}), timeout=120)
            ans = r.get("final_answer", "") or ""
            rec.update(mode=r.get("mode", ""), secs=round(time.time() - t0, 1),
                       chars=len(ans), urls=len(_URL.findall(ans)),
                       refusal=bool(_REFUSAL.search(ans)), ans=ans[:280], err="")
        except Exception as e:  # noqa: BLE001
            rec.update(mode="", secs=round(time.time() - t0, 1), chars=0, urls=0,
                       refusal=False, ans="", err=f"{type(e).__name__}: {e}"[:160])
        async with _WLOCK:  # инкрементально на диск — частичный прогон не теряется при сбое
            with open(_OUT, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
        try:
            print(f"[{rec['secs']:>5}s] {cat:24} mode={rec.get('mode',''):11} url={rec['urls']} :: {q[:50]}", flush=True)
        except BrokenPipeError:
            pass
        return rec


async def main():
    from main import make_checkpointer
    from src.agent import build_graph
    from src import hitl
    hitl.set_work_mode("auto")

    items = _flatten()
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else len(items)
    conc = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    items = items[:limit]
    open(_OUT, "w").close()  # свежий файл под инкрементальную запись
    print(f"=== БЕНЧ: {len(items)} запросов, concurrency={conc} ===")

    async with make_checkpointer() as cp:
        graph = build_graph(cp)
        sem = asyncio.Semaphore(conc)
        results = await asyncio.gather(*[_run_one(graph, c, q, sem) for c, q in items])

    with open("/tmp/bench_results.jsonl", "w", encoding="utf-8") as f:
        for r in results:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # ── Агрегат ──
    print("\n" + "=" * 78 + "\nИТОГИ ПО КАТЕГОРИЯМ\n" + "=" * 78)
    cats = {}
    for r in results:
        c = cats.setdefault(r["cat"], {"n": 0, "err": 0, "refuse": 0, "secs": 0.0,
                                       "url": 0, "ground_ok": 0, "ground_exp": 0, "modes": {}})
        c["n"] += 1
        c["err"] += bool(r["err"])
        c["refuse"] += bool(r["refusal"])
        c["secs"] += r["secs"]
        c["url"] += bool(r["urls"])
        if r["should_ground"]:
            c["ground_exp"] += 1
            # заземлился = пошёл в путь с инструментами (act/deliberate/heavy) и НЕ упал
            if r.get("mode") in ("act", "deliberate", "heavy") and not r["err"]:
                c["ground_ok"] += 1
        c["modes"][r.get("mode", "")] = c["modes"].get(r.get("mode", ""), 0) + 1
    print(f"{'категория':24} {'n':>3} {'ok':>3} {'err':>3} {'avg_s':>6} {'с_url':>6} {'grnd':>8}")
    tot = {"n": 0, "err": 0, "url": 0, "ge": 0, "go": 0, "secs": 0.0}
    for cat, c in cats.items():
        gr = f"{c['ground_ok']}/{c['ground_exp']}" if c["ground_exp"] else "-"
        print(f"{cat:24} {c['n']:>3} {c['n']-c['err']:>3} {c['err']:>3} "
              f"{c['secs']/c['n']:>6.1f} {c['url']:>6} {gr:>8}")
        tot["n"] += c["n"]; tot["err"] += c["err"]; tot["url"] += c["url"]
        tot["ge"] += c["ground_exp"]; tot["go"] += c["ground_ok"]; tot["secs"] += c["secs"]
    print("-" * 78)
    print(f"{'ВСЕГО':24} {tot['n']:>3} {tot['n']-tot['err']:>3} {tot['err']:>3} "
          f"{tot['secs']/max(tot['n'],1):>6.1f} {tot['url']:>6} "
          f"{tot['go']}/{tot['ge']} заземлено")
    # Распределение режимов
    allmodes = {}
    for r in results:
        allmodes[r.get("mode", "")] = allmodes.get(r.get("mode", ""), 0) + 1
    print("Режимы:", ", ".join(f"{k or '(пусто)'}={v}" for k, v in sorted(allmodes.items(), key=lambda x: -x[1])))
    print("Лог: /tmp/bench_results.jsonl")


if __name__ == "__main__":
    asyncio.run(main())
